/** Minimal definition for registering a feature unit. */
export interface SubagentDefinition {
  name: string;
  description: string;
  domain: string;

  /** If set, used as-is for the system prompt (bypasses convention file loading). */
  systemPrompt?: string;

  // Caller-managed paths (persisted for resume)
  /** Agent directory containing AGENTS.md, heartbeat.md, knowledge/, workspace/, etc. */
  agentDir?: string;
  /** Canonical installation-relative owner for recovery and completion, not the immutable source directory. */
  agentRelativeDir?: string;
  /** Explicit stable installation owner for programmatic definitions. Required
   * for shared execution admission when no directory identity exists. */
  hostIdentity?: string;
  workspace?: string;
  /** Directory containing agent knowledge files (INDEX.md, etc.). */
  knowledgeDir?: string;

  /** App ownership metadata used to enforce external/app-local call boundaries. */
  appLocal?: boolean;
  projectId?: string;

  /** Project root / exec cwd. Injected into system prompt as a concrete runtime fact. */
  projectRoot?: string;

  /** Immutable shared prompt/skill source selected with this definition generation. */
  sharedRoot?: string;

  /** Trusted file-tool scope captured with this definition. */
  fileWritePolicy?: FileWritePolicy;

  // Capabilities
  tools: AgentTool[];
  model: Model<any>;
  apiKey?: string;
  timeoutMs?: number;

  /**
   * Custom prefix for session IDs generated by run().
   * Defaults to "s" if not set, producing IDs like "s_1234567890_0".
   * When set to e.g. "agent", produces IDs like "agent_1234567890_0".
   */
  sessionIdPrefix?: string;

  /** Enable automatic context compaction for long-running sessions. */
  compaction?: boolean;

  /** Restrict direct LLM subagent tool visibility while keeping workflow calls open. */
  callableFrom?: "all" | "workflow";

  /** Optional context adapter captured with this immutable definition generation. */
  contextPreparation?: AgentContextPreparer;
  /** Loader-captured entrypoint identity; not an App-supplied metric label. */
  contextPreparationSource?: { path: string; entryHash: string };

  /** Validated skill snapshot retained with this definition by each live session. */
  skillCatalog?: SkillCatalog;
  /** Optional pre-read AGENTS.md identity text captured at catalog snapshot time. */
  identityText?: string;
  /** Optional pre-read shared/common-sense.md text captured at catalog snapshot time. */
  sharedPromptText?: string;
}

