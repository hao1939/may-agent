/**
 * log.ts — Global logging for may-agent.
 *
 * One function: log(level, message). Usable from anywhere in the codebase
 * (lib, app, handlers). No dependency on EventBus.
 *
 * Subscribers can be added via addLogSubscriber(). Console output is always
 * on by default. Additional subscribers (web UI, socket UI, etc.) are added
 * at startup. This is a separate channel from EventBus — no circular
 * dependency possible.
 */

export type LogLevel = "debug" | "info" | "warn" | "error";
export type LogSubscriber = (level: LogLevel, message: string) => void;

const consoleSubscriber: LogSubscriber = (level, msg) => {
  if (level === "error") console.error(msg);
  else if (level === "warn") console.warn(msg);
  else if (level === "debug") {
    /* silent by default */
  } else console.log(msg);
};

let _subscribers: LogSubscriber[] = [consoleSubscriber];

/** Add a log subscriber. Returns an unsubscribe function. */
export function addLogSubscriber(fn: LogSubscriber): () => void {
  _subscribers.push(fn);
  return () => {
    _subscribers = _subscribers.filter((s) => s !== fn);
  };
}

/** Log a message to all subscribers. */
export function log(level: LogLevel, message: string): void {
  for (const fn of _subscribers) {
    try {
      fn(level, message);
    } catch {
      /* subscriber errors never break logging */
    }
  }
}

import { ExecutionDeferredError, type ExecutionResult } from "@may-agent/sdk/app";
import type { CliCallFacts } from "@may-agent/sdk/app";

export function cliCallFacts(sessionId: string, messages: AgentMessage[], limit = 64): CliCallFacts[] {
  const calls = new Map<string, CliCallFacts>();
  for (const message of messages) {
    if (message.role !== "toolResult" || message.toolName !== "run_cli_agent") continue;
    const call = (message.details as { cliCall?: CliCallFacts } | undefined)?.cliCall;
    if (!call || call.sessionId !== sessionId || call.toolCallId !== message.toolCallId) continue;
    if (!call.taskId || (call.tool !== "codex" && call.tool !== "claude")) continue;
    if (call.status !== "completed" && call.status !== "failed") continue;
    if (!call.resultPath || !call.structuredResultPath || !call.eventsPath) continue;
    calls.set(call.taskId, call);
  }
  const normalizedLimit = Number.isFinite(limit) ? Math.max(0, Math.floor(limit)) : 0;
  return normalizedLimit === 0 ? [] : [...calls.values()].slice(-normalizedLimit);
}

export type WorkflowToolResult = (
  | { type: "done"; summary: string; output?: unknown; facts?: unknown }
  | { type: "blocked"; reason: string; context?: unknown; output?: unknown; facts?: unknown }
  | { type: "error"; error: string; partialContext?: string; output?: unknown; facts?: unknown }
  | { type: "interrupted"; steeringMessage: string; output?: unknown; facts?: unknown }
  | { type: "list"; workflows: { name: string; description: string; inputSchema?: Record<string, unknown> }[] }
) & {
  workflowRunId?: string;
  sessionIds?: string[];
};

/** Enforce required finish() and optional schema-backed result payload on workflow prompt steps. */
export function enforceStructuredWorkflowResult(result: TaskResult, expectsPayload: boolean): TaskResult {
  if (result.status !== "done") return result;
  if (!result.finishResult) {
    return {
      ...result,
      status: "error",
      error: "Workflow agent step completed without the required finish() result",
    };
  }
  if (
    expectsPayload &&
    result.finishResult.status === "done" &&
    result.structuredResult === undefined &&
    result.finishResult.output === undefined
  ) {
    return {
      ...result,
      status: "error",
      error: "Workflow agent step completed without the required schema-backed finish().output payload",
    };
  }
  return result;
}

/** Project execution evidence for callers; never accepts the owning Task. */
export function agentExecutionResult(result: TaskResult): ExecutionResult {
  if (!result.sessionId) throw new Error(result.error || result.errorMessage || "Agent call did not start an execution");
  const finish = result.finishResult;
  const status = result.status === "interrupted"
    ? "interrupted"
    : result.status === "error" || finish?.status === "error"
      ? "error"
      : finish?.status === "blocked"
        ? "blocked"
        : "done";
  return {
    id: result.sessionId,
    status,
    summary:
      (result.status === "error" ? result.error?.trim() || result.errorMessage?.trim() : undefined) ||
      finish?.summary?.trim() || result.lastAssistantText?.trim() || result.error?.trim() ||
      `Agent execution ${status}`,
    ...(result.structuredResult !== undefined
      ? { output: result.structuredResult }
      : finish?.output !== undefined ? { output: finish.output } : {}),
    ...(finish?.facts !== undefined ? { facts: finish.facts } : {}),
  };
}

/** Setup failures have no execution identity. Do not fabricate an evidence link. */
export function workflowExecutionResult(result: WorkflowToolResult): ExecutionResult | undefined {
  if (result.type === "list" || !result.workflowRunId) return undefined;
  return {
    id: result.workflowRunId,
    status: result.type,
    summary: result.type === "done" ? result.summary
      : result.type === "blocked" ? result.reason
        : result.type === "interrupted" ? result.steeringMessage : result.error,
    ...(result.output !== undefined ? { output: result.output } : {}),
    ...(result.facts !== undefined ? { facts: result.facts }
      : result.type === "blocked" && result.context !== undefined ? { facts: result.context } : {}),
  };
}

/** Model tools expose non-start as data without fabricating a terminal result ID. */
export function deferredExecutionResult(error: ExecutionDeferredError) {
  return {
    status: "deferred" as const,
    started: false as const,
    summary: error.message,
    deferral: error.deferral,
    ...(error.callerExecution ? { callerExecution: error.callerExecution } : {}),
  };
}

/**
 * classify-error.ts — Pure string-matching error classifier.
 *
 * Kept standalone to avoid any transitive dependency on bun:sqlite
 * when consumers only need error classification.
 */

export type ErrorClass = "infra" | "logic" | "abort" | "overflow";

/**
 * Classify an error string into a category.
 * Pure function — no IO, no database, no Bun-specific deps.
 */
export function classifyError(error: string | undefined | null): ErrorClass {
  if (!error) return "logic";
  const e = error.toLowerCase();

  // Infrastructure errors (retryable)
  if (
    e.includes("empty response") ||
    e.includes("0 output tokens") ||
    e.includes("stream error") ||
    e.includes("stream closed") ||
    e.includes("502") ||
    e.includes("503") ||
    e.includes("429") ||
    e.includes("econnreset") ||
    e.includes("rate limit") ||
    e.includes("timeout") ||
    e.includes("connection") ||
    e.includes("network") ||
    e.includes("no deployments available for selected model") ||
    (e.includes("model is not supported") && e.includes("model group")) ||
    (e.includes("bad request") && e.includes("model group"))
  ) {
    return "infra";
  }

  // Context overflow (not retryable without modification)
  if (
    e.includes("context window") ||
    e.includes("max tokens") ||
    e.includes("context_length_exceeded") ||
    e.includes("too many tokens")
  ) {
    return "overflow";
  }

  // Abort (user or system initiated)
  if (e.includes("abort") || e.includes("cancel")) {
    return "abort";
  }

  // Logic errors (not retryable — bug or permission issue)
  if (
    e.includes("tool not found") ||
    e.includes("permission denied") ||
    e.includes("call depth exceeded") ||
    e.includes("not allowed") ||
    e.includes("401") ||
    e.includes("403") ||
    e.includes("unauthorized") ||
    e.includes("forbidden")
  ) {
    return "logic";
  }

  // Default to logic (conservative — unknown errors shouldn't auto-retry)
  return "logic";
}

