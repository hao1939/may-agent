import {
  existsSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import type { ProjectAppContext } from "@may-agent/sdk";

type FeedbackContext = ProjectAppContext & {
  query: NonNullable<ProjectAppContext["query"]>;
};

type EvaluationRow = {
  sessionId: string;
  quality: number;
  verdict: string;
  issues: string;
  createdAt: number;
};

function rows<T>(value: unknown): T[] {
  if (Array.isArray(value)) return value as T[];
  return ((value as { rows?: T[] } | undefined)?.rows ?? []) as T[];
}

function configuredName(agentDir: string, fallback: string): string | null {
  const configPath = join(agentDir, "agent.json");
  if (!existsSync(configPath)) return null;
  try {
    const config = JSON.parse(readFileSync(configPath, "utf8")) as {
      name?: string;
      disabled?: boolean;
    };
    if (config.disabled) return null;
    return config.name ?? fallback;
  } catch {
    return fallback;
  }
}

function resolveAgentDir(projectRoot: string, agent: string): string | null {
  const projectsRoot = join(projectRoot, "projects");
  if (existsSync(projectsRoot)) {
    for (const app of readdirSync(projectsRoot, { withFileTypes: true })) {
      if (!app.isDirectory() || !app.name.endsWith(".app")) continue;
      const agentsRoot = join(projectsRoot, app.name, "agents");
      if (!existsSync(agentsRoot)) continue;
      for (const candidate of readdirSync(agentsRoot, {
        withFileTypes: true,
      })) {
        if (!candidate.isDirectory()) continue;
        const candidateDir = join(agentsRoot, candidate.name);
        if (configuredName(candidateDir, candidate.name) === agent) {
          return candidateDir;
        }
      }
    }
  }

  const globalDir = join(projectRoot, "agents", agent);
  return configuredName(globalDir, agent) === agent ? globalDir : null;
}

function parseIssues(value: string): string[] {
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed)
      ? parsed.filter((item): item is string => typeof item === "string")
      : [];
  } catch {
    return [];
  }
}

function projectAgentFeedback(
  ctx: FeedbackContext,
  projectRoot: string,
  agent: string,
  now: number,
): boolean {
  const agentDir = resolveAgentDir(projectRoot, agent);
  if (!agentDir) return false;

  const feedbackPath = join(agentDir, "last-eval.md");
  const latest = rows<EvaluationRow>(
    ctx.query.sql(
      `SELECT sessionId, quality, verdict, issues, createdAt
         FROM evaluations
        WHERE agent = ? AND issues IS NOT NULL AND issues != '[]'
        ORDER BY createdAt DESC LIMIT 1`,
      [agent],
      { limit: 1 },
    ),
  )[0];

  if (!latest) {
    if (existsSync(feedbackPath)) unlinkSync(feedbackPath);
    return false;
  }

  const recent = rows<{ issues: string }>(
    ctx.query.sql(
      `SELECT DISTINCT issues FROM evaluations
        WHERE agent = ? AND issues IS NOT NULL AND issues != '[]'
          AND createdAt > ?
        ORDER BY createdAt DESC LIMIT 5`,
      [agent, now - 7 * 86_400_000],
      { limit: 5 },
    ),
  );
  const latestIssues = parseIssues(latest.issues);
  const recentIssues = Array.from(
    new Set(recent.flatMap((row) => parseIssues(row.issues))),
  );

  writeFileSync(
    feedbackPath,
    `# Last Evaluation Feedback
<!-- Auto-generated by evaluation.app. Do not edit manually. -->

**Latest session:** ${latest.sessionId}
**Verdict:** ${latest.verdict} (quality: ${latest.quality})
**When:** ${new Date(latest.createdAt).toISOString()}

## Issues Flagged

${latestIssues.map((issue) => `- ${issue}`).join("\n")}

## Recent Issue Patterns (last 5 evaluations)

${recentIssues.map((issue) => `- ${issue}`).join("\n")}

## Action Required

Review these issues before starting work. If the same issue appears repeatedly,
prioritize avoiding it in this session. Acknowledge it in your plan when relevant.
`,
  );
  return true;
}

export function projectEvaluationFeedback(
  ctx: FeedbackContext,
  now = Date.now(),
): unknown {
  const projectRoot = resolve(ctx.appPath("../.."));
  const agents = rows<{ agent: string }>(
    ctx.query.sql(
      `SELECT DISTINCT agent FROM evaluations
        WHERE issues IS NOT NULL AND issues != '[]' AND createdAt > ?`,
      [now - 7 * 86_400_000],
      { limit: 500 },
    ),
  );

  let updated = 0;
  for (const { agent } of agents) {
    if (projectAgentFeedback(ctx, projectRoot, agent, now)) updated++;
  }
  return ctx.noop(`Projected evaluation feedback for ${updated} agents.`);
}
