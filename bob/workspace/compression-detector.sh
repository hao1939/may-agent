#!/bin/bash
# H-EXP-020 Phase 2: Knowledge Compression Detector
# Scans recent session checkpoints for promotable insights
# Cross-references against existing KEs to avoid duplication
# Outputs promotion candidates with suggested compression level

set -euo pipefail

CHECKPOINT_DIR=".state/checkpoints"
KE_DIR="agents/shared/knowledge/entries"
OUTPUT="agents/bob/workspace/compression-candidates.md"
N_SESSIONS=${1:-20}  # How many recent sessions to scan

echo "# Compression Candidates — $(date +%Y-%m-%d)" > "$OUTPUT"
echo "" >> "$OUTPUT"
echo "Auto-generated by compression-detector.sh (H-EXP-020 Phase 2)" >> "$OUTPUT"
echo "Scanned last $N_SESSIONS session checkpoints." >> "$OUTPUT"
echo "" >> "$OUTPUT"

# Step 1: Extract all summaries and decisions from recent checkpoints
TEMP_INSIGHTS=$(mktemp)
for f in $(ls "$CHECKPOINT_DIR"/s_*.jsonl 2>/dev/null | tail -"$N_SESSIONS"); do
    session=$(basename "$f" .jsonl)
    # Extract summary and decisions using basic parsing
    while IFS= read -r line; do
        summary=$(echo "$line" | grep -oP '"summary":"[^"]*"' | sed 's/"summary":"//;s/"$//' || true)
        agent=$(echo "$line" | grep -oP '"agentName":"[^"]*"' | sed 's/"agentName":"//;s/"$//' || true)
        decisions=$(echo "$line" | grep -oP '"decisions":\[[^\]]*\]' || true)
        next_steps=$(echo "$line" | grep -oP '"next_steps":\[[^\]]*\]' || true)
        
        if [ -n "$summary" ]; then
            echo "$agent|$session|SUMMARY|$summary" >> "$TEMP_INSIGHTS"
        fi
        if [ -n "$decisions" ]; then
            # Extract individual decisions
            echo "$decisions" | grep -oP '"[^"]{10,}"' | while read -r d; do
                d_clean=$(echo "$d" | sed 's/^"//;s/"$//')
                echo "$agent|$session|DECISION|$d_clean" >> "$TEMP_INSIGHTS"
            done
        fi
    done < "$f"
done

total=$(wc -l < "$TEMP_INSIGHTS")
echo "Extracted $total insights from $N_SESSIONS sessions." >> "$OUTPUT"
echo "" >> "$OUTPUT"

# Step 2: Build KE title index for dedup checking
TEMP_KE_TITLES=$(mktemp)
for ke in "$KE_DIR"/KE-*.md; do
    title=$(head -1 "$ke" | sed 's/^# //')
    echo "$title" >> "$TEMP_KE_TITLES"
done

# Step 3: Find repeated keywords/themes across sessions
echo "## Repeated Themes (cross-session)" >> "$OUTPUT"
echo "" >> "$OUTPUT"

# Extract key phrases (3+ word sequences that appear in 2+ sessions)
TEMP_KEYWORDS=$(mktemp)
while IFS='|' read -r agent session type insight; do
    # Lowercase, extract meaningful phrases
    echo "$insight" | tr '[:upper:]' '[:lower:]' | \
        grep -oP '\b[a-z][-a-z]+(?:\s+[a-z][-a-z]+){1,3}\b' | \
        sort -u | while read -r phrase; do
            echo "$session|$phrase"
        done
done < "$TEMP_INSIGHTS" > "$TEMP_KEYWORDS" 2>/dev/null || true

# Count phrases appearing in 2+ different sessions
TEMP_PHRASE_COUNTS=$(mktemp)
cut -d'|' -f2 "$TEMP_KEYWORDS" | sort | uniq -c | sort -rn | \
    awk '$1 >= 2 && length($0) > 20' | head -30 > "$TEMP_PHRASE_COUNTS"

while read -r count phrase; do
    # Check if already covered by a KE
    ke_match=$(grep -il "$phrase" "$TEMP_KE_TITLES" 2>/dev/null | wc -l || echo 0)
    if [ "$ke_match" -eq 0 ]; then
        status="⚠️ NO KE MATCH"
    else
        status="✅ Likely covered"
    fi
    echo "- **\"$phrase\"** — $count sessions — $status" >> "$OUTPUT"
done < "$TEMP_PHRASE_COUNTS"

echo "" >> "$OUTPUT"

# Step 4: Classify insights by compression level and promotion potential
echo "## Promotion Candidates" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "Insights that appear procedural/declarative and aren't covered by existing KEs:" >> "$OUTPUT"
echo "" >> "$OUTPUT"

candidate_count=0
while IFS='|' read -r agent session type insight; do
    # Check for declarative/procedural markers first
    is_promotable=false
    compression_level=""
    
    if echo "$insight" | grep -qiP '(discovered|confound|key finding|finding:|shifted|provides \+|lift|80pp|0%|drift|redundan|waste|fake|synthetic|invalid|ALL synthetic|gap is|real gap|strong .* effect|shows|worst.perform|highest.impact|no effect|ceiling|floor)'; then
        is_promotable=true
        compression_level="DECLARATIVE"
    elif echo "$insight" | grep -qiP '(must use|should be|needs to|pattern|reusable|gotcha|warning|blocked on|defaults to|doesn.t exist|fails due|already covered|maps to|not registered|previous data|invalidated|need infra)'; then
        is_promotable=true
        compression_level="PROCEDURAL"
    fi
    
    # Skip purely episodic unless promotable
    if [ "$is_promotable" = false ]; then
        continue
    fi
    
    if [ "$is_promotable" = true ]; then
        # Check against KE titles for duplication
        # Use first 3 significant words as search terms
        search_terms=$(echo "$insight" | tr '[:upper:]' '[:lower:]' | grep -oP '\b[a-z]{5,}\b' | grep -vP '(complete|created|built|updated|triaged|committed|session|agents?|should|needs|already|which|doesn|about|their|these|where|being|other|still|wrote|based)' | head -3 | tr '\n' '|' | sed 's/|$//')
        ke_hits=0
        if [ -n "$search_terms" ]; then
            # Use AND logic: all terms must appear in same KE
            first_term=$(echo "$search_terms" | cut -d'|' -f1)
            ke_hits=$(grep -rl "$first_term" "$KE_DIR"/KE-*.md 2>/dev/null | while read -r kf; do
                match=true
                for term in $(echo "$search_terms" | tr '|' ' '); do
                    grep -qi "$term" "$kf" || { match=false; break; }
                done
                $match && echo "$kf"
            done | wc -l || true)
            ke_hits=$(echo "$ke_hits" | tr -d '[:space:]')
            ke_hits=${ke_hits:-0}
        fi
        
        if [ "$ke_hits" -lt 2 ]; then
            candidate_count=$((candidate_count + 1))
            echo "### Candidate $candidate_count" >> "$OUTPUT"
            echo "- **Agent**: $agent | **Session**: $session" >> "$OUTPUT"
            echo "- **Type**: $type | **Level**: $compression_level" >> "$OUTPUT"
            echo "- **Insight**: $insight" >> "$OUTPUT"
            echo "- **KE overlap**: $ke_hits existing KEs with similar terms" >> "$OUTPUT"
            echo "" >> "$OUTPUT"
        fi
    fi
done < "$TEMP_INSIGHTS"

echo "" >> "$OUTPUT"
echo "## Summary" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "- Total insights scanned: $total" >> "$OUTPUT"
echo "- Promotion candidates: $candidate_count" >> "$OUTPUT"
echo "- Recommended action: Review candidates above, create KEs for high-value ones" >> "$OUTPUT"

# Cleanup
rm -f "$TEMP_INSIGHTS" "$TEMP_KE_TITLES" "$TEMP_KEYWORDS" "$TEMP_PHRASE_COUNTS"

echo "Done. Results at: $OUTPUT"
echo "Found $candidate_count promotion candidates from $total insights."
