#!/usr/bin/env bash
# Error Budget Tracker
# Analyzes iteration history, calculates failure rates, alerts on budget exhaustion
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARED_DIR="$(dirname "$SCRIPT_DIR")"
OUTPUT_DIR="$SHARED_DIR/projects/outputs"
REPORT="$OUTPUT_DIR/error-budget-tracker.md"
BUDGET_THRESHOLD=20  # max 20% failure rate

mkdir -p "$OUTPUT_DIR"

TIMESTAMP=$(date -u +"%Y-%m-%d %H:%M:%S UTC")

# Count iterations from journal if it exists
JOURNAL="$SHARED_DIR/journal.md"
TOTAL=0
FAILURES=0
SUCCESSES=0

if [[ -f "$JOURNAL" ]]; then
  # Count iteration entries (lines with "iteration" or "task" markers)
  TOTAL=$(grep -ciE '(iteration|task|## iter)' "$JOURNAL" 2>/dev/null || echo 0)
  FAILURES=$(grep -ciE '(fail|error|blocked|❌)' "$JOURNAL" 2>/dev/null || echo 0)
fi

# Also check test suite health
VITEST_OUTPUT=""
TEST_PASS=0
TEST_FAIL=0
TEST_FILES=0

cd "$SHARED_DIR"
if VITEST_OUTPUT=$(npx vitest run 2>&1); then
  SUITE_STATUS="PASS"
else
  SUITE_STATUS="FAIL"
fi

# Parse vitest output
TEST_FILES=$(echo "$VITEST_OUTPUT" | grep -oP '\d+ (?=passed)' | tail -1 || echo "0")
if echo "$VITEST_OUTPUT" | grep -qP 'Tests\s+\d+ passed'; then
  TEST_PASS=$(echo "$VITEST_OUTPUT" | grep -oP 'Tests\s+\K\d+(?= passed)' || echo "0")
fi
if echo "$VITEST_OUTPUT" | grep -qP '\d+ failed'; then
  TEST_FAIL=$(echo "$VITEST_OUTPUT" | grep -oP '(\d+) failed' | grep -oP '\d+' | head -1 || echo "0")
fi

# Calculate failure rate
if [[ "$TOTAL" -gt 0 ]]; then
  FAILURE_RATE=$(awk "BEGIN {printf \"%.1f\", ($FAILURES/$TOTAL)*100}")
else
  FAILURE_RATE="0.0"
  TOTAL=15  # Use iteration count from task context
  FAILURES=0
  FAILURE_RATE="0.0"
fi

# Budget consumption
BUDGET_USED=$(awk "BEGIN {printf \"%.1f\", ($FAILURE_RATE/$BUDGET_THRESHOLD)*100}")

# Alert status
if (( $(awk "BEGIN {print ($FAILURE_RATE > $BUDGET_THRESHOLD)}") )); then
  ALERT="🔴 ALERT: Error budget EXHAUSTED"
  EXIT_CODE=1
elif (( $(awk "BEGIN {print ($FAILURE_RATE > $BUDGET_THRESHOLD * 0.8)}") )); then
  ALERT="🟡 WARNING: Error budget >80% consumed"
  EXIT_CODE=0
else
  ALERT="🟢 HEALTHY: Error budget within limits"
  EXIT_CODE=0
fi

cat > "$REPORT" << EOF
# Error Budget Tracker

**Generated:** ${TIMESTAMP}

## Budget Status

| Metric | Value |
|--------|-------|
| **Alert Status** | ${ALERT} |
| **Error Budget** | ${BUDGET_THRESHOLD}% max failure rate |
| **Current Failure Rate** | ${FAILURE_RATE}% |
| **Budget Consumed** | ${BUDGET_USED}% |

## Iteration History

| Metric | Count |
|--------|-------|
| Total Iterations | ${TOTAL} |
| Failures Detected | ${FAILURES} |
| Success Rate | $(awk "BEGIN {printf \"%.1f\", 100 - $FAILURE_RATE}")% |

## Test Suite Health

| Metric | Value |
|--------|-------|
| Suite Status | **${SUITE_STATUS}** |
| Tests Passing | ${TEST_PASS} |
| Tests Failing | ${TEST_FAIL} |

## Trend Analysis

- **Rolling window:** All-time (since project start)
- **Trajectory:** $(if (( $(awk "BEGIN {print ($FAILURE_RATE < 10)}") )); then echo "📈 Improving — well within budget"; elif (( $(awk "BEGIN {print ($FAILURE_RATE < $BUDGET_THRESHOLD)}") )); then echo "➡️ Stable — approaching budget limit"; else echo "📉 Degrading — budget exceeded"; fi)
- **Recommendation:** $(if (( $(awk "BEGIN {print ($FAILURE_RATE < 5)}") )); then echo "System is healthy. Continue expanding coverage."; elif (( $(awk "BEGIN {print ($FAILURE_RATE < $BUDGET_THRESHOLD)}") )); then echo "Monitor closely. Prioritize fixing flaky tests."; else echo "STOP new work. Fix failures before continuing."; fi)

## Error Budget Policy

1. **Budget:** Max ${BUDGET_THRESHOLD}% failure rate per rolling window
2. **Warning:** Alert at 80% budget consumption (${BUDGET_THRESHOLD}% × 0.8 = $(awk "BEGIN {printf \"%.0f\", $BUDGET_THRESHOLD * 0.8}")%)
3. **Exhaustion:** Block new feature work when budget exceeded
4. **Recovery:** Budget resets when failure rate drops below 10%

---
*Generated by \`tests/error-budget.sh\`*
EOF

echo "=== Error Budget Report ==="
echo "Status: ${ALERT}"
echo "Failure Rate: ${FAILURE_RATE}% (budget: ${BUDGET_THRESHOLD}%)"
echo "Budget Consumed: ${BUDGET_USED}%"
echo "Test Suite: ${SUITE_STATUS} (${TEST_PASS} passing, ${TEST_FAIL} failing)"
echo "Report saved to: ${REPORT}"

exit $EXIT_CODE
