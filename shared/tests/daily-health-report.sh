#!/bin/bash
# Daily Health Report Generator
# Runs test suite and scans project statuses, outputs markdown report

set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARED_DIR="$(dirname "$SCRIPT_DIR")"
ROOT_DIR="$(dirname "$SHARED_DIR")"
OUTPUT_DIR="$ROOT_DIR/projects/closed-loop-reliability/outputs"
REPORT_FILE="$OUTPUT_DIR/daily-health-report.md"
TIMESTAMP=$(date -u '+%Y-%m-%d %H:%M:%S UTC')

mkdir -p "$OUTPUT_DIR"

# Run test suite
cd "$ROOT_DIR"
TEST_OUTPUT=$(bun run test 2>&1)
TEST_EXIT=$?

# Parse test counts
TESTS_PASSED=$(echo "$TEST_OUTPUT" | grep -oP '\d+(?= passed)' | tail -1)
TESTS_FAILED=$(echo "$TEST_OUTPUT" | grep -oP '\d+(?= failed)' | tail -1)
TEST_FILES=$(echo "$TEST_OUTPUT" | grep 'Test Files' | grep -oP '\d+(?= passed)' | head -1)

TESTS_PASSED=${TESTS_PASSED:-0}
TESTS_FAILED=${TESTS_FAILED:-0}
TEST_FILES=${TEST_FILES:-0}

if [ $TEST_EXIT -eq 0 ]; then
  SUITE_STATUS="✅ PASS"
else
  SUITE_STATUS="❌ FAIL"
fi

# Scan project statuses
PROJECT_TABLE=""
for proj_dir in "$ROOT_DIR"/projects/*/; do
  [ -d "$proj_dir" ] || continue
  proj_name=$(basename "$proj_dir")
  [ "$proj_name" = "outputs" ] && continue
  proj_file="$proj_dir/project.md"
  if [ -f "$proj_file" ]; then
    status=$(grep -i '^status:' "$proj_file" | head -1 | sed 's/^[Ss]tatus:\s*//')
    [ -z "$status" ] && status=$(grep -i '^\*\*status\*\*' "$proj_file" | head -1 | sed 's/.*:\s*//')
    [ -z "$status" ] && status="unknown"
    PROJECT_TABLE="$PROJECT_TABLE| $proj_name | $status |\n"
  fi
done

# Generate report
cat > "$REPORT_FILE" << EOF
# Daily Health Report

**Generated:** $TIMESTAMP

## Test Suite Summary

| Metric | Value |
|--------|-------|
| Status | $SUITE_STATUS |
| Test Files | $TEST_FILES |
| Tests Passed | $TESTS_PASSED |
| Tests Failed | $TESTS_FAILED |

## Project Status

| Project | Status |
|---------|--------|
$(echo -e "$PROJECT_TABLE")

## Notes

- Full test output available via \`cd /app/agents/shared && npx vitest run\`
- Report auto-generated by \`tests/daily-health-report.sh\`
EOF

echo "Report generated: $REPORT_FILE"
echo "Suite: $SUITE_STATUS | $TESTS_PASSED passed, $TESTS_FAILED failed in $TEST_FILES files"
exit $TEST_EXIT
