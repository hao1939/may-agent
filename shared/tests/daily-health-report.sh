#!/bin/bash
# Daily Health Report Generator
# Runs test suite and canonical workflow audit, outputs markdown report

set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARED_DIR="$(dirname "$SCRIPT_DIR")"
ROOT_DIR="$(dirname "$SHARED_DIR")"
OUTPUT_DIR="${DAILY_HEALTH_OUTPUT_DIR:-$ROOT_DIR/.state/health-reports}"
REPORT_FILE="$OUTPUT_DIR/daily-health-report.md"
TIMESTAMP=$(date -u '+%Y-%m-%d %H:%M:%S UTC')

mkdir -p "$OUTPUT_DIR"

# Run test suite
cd "$ROOT_DIR"
TEST_OUTPUT=$(bun run test 2>&1)
TEST_EXIT=$?

# Parse test counts
TESTS_PASSED=$(echo "$TEST_OUTPUT" | grep -oE '\b[0-9]+ pass\b' | tail -1 | grep -oE '[0-9]+')
TESTS_FAILED=$(echo "$TEST_OUTPUT" | grep -oE '\b[0-9]+ fail\b' | tail -1 | grep -oE '[0-9]+')
TEST_FILES=$(echo "$TEST_OUTPUT" | grep -oE 'across [0-9]+ files?' | tail -1 | grep -oE '[0-9]+')

TESTS_PASSED=${TESTS_PASSED:-0}
TESTS_FAILED=${TESTS_FAILED:-0}
TEST_FILES=${TEST_FILES:-0}

if [ $TEST_EXIT -eq 0 ]; then
  SUITE_STATUS="✅ PASS"
else
  SUITE_STATUS="❌ FAIL"
fi

# Run canonical workflow audit
WORKFLOW_AUDIT_MD=$(bun scripts/audit-workflows.ts --markdown 2>&1)
AUDIT_EXIT=$?

# Generate report
cat > "$REPORT_FILE" << EOF
# Daily Health Report

**Generated:** $TIMESTAMP

## Test Suite Summary

| Metric | Value |
|--------|-------|
| Status | $SUITE_STATUS |
| Test Files | $TEST_FILES |
| Tests Passed | $TESTS_PASSED |
| Tests Failed | $TESTS_FAILED |

$WORKFLOW_AUDIT_MD

## Notes

- Full test output available via \`cd /app && bun run test\`
- Workflow audit available via \`cd /app && bun run audit:workflows\`
- Report auto-generated by \`shared/tests/daily-health-report.sh\`
EOF

echo "Report generated: $REPORT_FILE"
echo "Suite: $SUITE_STATUS | $TESTS_PASSED passed, $TESTS_FAILED failed in $TEST_FILES files"
if [ $TEST_EXIT -ne 0 ]; then
  exit $TEST_EXIT
fi
exit $AUDIT_EXIT
