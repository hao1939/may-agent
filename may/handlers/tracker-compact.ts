/**
 * tracker-compact — Pre-generates a compact status index from the
 * common-sense-tracker.md (45KB) so the LLM only needs to read ~3KB.
 *
 * Problem: Coach's common-sense-verify cron reads the full 45KB tracker
 * every run (~6 runs/day). The tracker has 39 items with inline evidence
 * averaging 700B each. The LLM only needs: item ID, name, status, and
 * last-verified date to pick which item to verify next.
 *
 * Solution: This handler runs as a cron job (every 4h, just before
 * common-sense-verify) and generates a compact status-only index at
 * agents/coach/workspace/common-sense-status.md (~3KB vs 45KB = 93% reduction).
 *
 * Savings: ~42KB × 6 runs/day = ~252KB/day of LLM input tokens saved.
 * At ~$4/MB, that's ~$1/day. But the real savings is reduced hallucination
 * risk and faster session completion (fewer turns needed to find next item).
 *
 * Usage in cron.json:
 *   {
 *     "name": "tracker-compact",
 *     "type": "handler",
 *     "handler": "tracker-compact",
 *     "intervalMs": 14400000,
 *     "enabled": true,
 *     "description": "Generate compact status index from common-sense tracker"
 *   }
 *
 * Then update common-sense-verify message to reference the compact file:
 *   "check workspace/common-sense-status.md for which item to verify next"
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import type { HandlerContext, HandlerModule } from "../../../src/lib/handler-context.js";
import type { CronEntry } from "../../../src/lib/cron-tool.js";

interface TrackerEntry {
  id: string;
  name: string;
  owner: string;
  status: string;
  agents: string;
  date: string;
}

function parseTracker(content: string): TrackerEntry[] {
  const entries: TrackerEntry[] = [];
  const lines = content.split("\n");

  for (const line of lines) {
    // Match table rows: | ID | Name | Owner | Status | Agents | Evidence | Date |
    if (!line.startsWith("| ") || line.startsWith("| #") || line.startsWith("|---")) {
      continue;
    }

    const parts = line.split("|").map(p => p.trim());
    // parts[0] = empty (before first |), parts[1] = ID, parts[2] = Name, etc.
    if (parts.length >= 8) {
      entries.push({
        id: parts[1],
        name: parts[2],
        owner: parts[3],
        status: parts[4],
        agents: parts[5],
        date: parts[7],
      });
    }
  }

  return entries;
}

function generateCompactIndex(entries: TrackerEntry[]): string {
  const lines: string[] = [];

  lines.push("# Common Sense Verification Status (Compact)");
  lines.push("");
  lines.push("_Auto-generated by tracker-compact handler. Full evidence in common-sense-tracker.md._");
  lines.push("");

  // Summary stats
  const verified = entries.filter(e => e.status.includes("✅")).length;
  const failed = entries.filter(e => e.status.includes("❌")).length;
  const partial = entries.filter(e => e.status.includes("⚠️")).length;
  const total = entries.length;

  lines.push(`**Summary**: ${verified} ✅ verified, ${partial} ⚠️ partial, ${failed} ❌ failed — ${total} total`);
  lines.push("");

  // Priority: items that need re-verification (oldest date, or failed/partial status)
  const needsWork = entries
    .filter(e => e.status.includes("❌") || e.status.includes("⚠️"))
    .sort((a, b) => (a.date || "").localeCompare(b.date || ""));

  if (needsWork.length > 0) {
    lines.push("## Needs Attention (❌ / ⚠️ — oldest first)");
    lines.push("");
    lines.push("| # | Item | Status | Last Verified |");
    lines.push("|---|------|--------|---------------|");
    for (const e of needsWork) {
      lines.push(`| ${e.id} | ${e.name} | ${e.status} | ${e.date} |`);
    }
    lines.push("");
  }

  // All items compact table
  lines.push("## All Items");
  lines.push("");
  lines.push("| # | Item | Status | Last Verified |");
  lines.push("|---|------|--------|---------------|");
  for (const e of entries) {
    lines.push(`| ${e.id} | ${e.name} | ${e.status} | ${e.date} |`);
  }
  lines.push("");
  lines.push(`_Generated: ${new Date().toISOString()}_`);

  return lines.join("\n");
}

export const create: HandlerModule["create"] = (ctx: HandlerContext, _entry: CronEntry) => {
  return async () => {
    const trackerPath = resolve(ctx.projectRoot, "agents/coach/workspace/common-sense-tracker.md");
    const outputPath = resolve(ctx.projectRoot, "agents/coach/workspace/common-sense-status.md");

    if (!existsSync(trackerPath)) {
      ctx.log("[tracker-compact] Tracker not found, skipping");
      return;
    }

    const content = readFileSync(trackerPath, "utf-8");
    const entries = parseTracker(content);

    if (entries.length === 0) {
      ctx.log("[tracker-compact] No entries found in tracker, skipping");
      return;
    }

    const compact = generateCompactIndex(entries);

    // Ensure directory exists
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, compact);

    ctx.log(`[tracker-compact] Generated compact index: ${entries.length} entries, ${compact.length} bytes (tracker was ${content.length} bytes)`);
  };
};
